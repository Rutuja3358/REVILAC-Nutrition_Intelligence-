'use strict';
const assert = require('assert');
const fs = require('fs');
const html = fs.readFileSync('index.html','utf8');
const server = fs.readFileSync('local-server.js','utf8');
const env = fs.readFileSync('.env.example','utf8');
assert(html.includes('rvn26-online-query') && html.includes('rvn26-online-search'),'online food lookup UI exists');
assert(html.includes("fetch('/api/food-search?q='+encodeURIComponent(q)"),'UI uses same-origin server proxy');
assert(server.includes("pathname === '/api/food-search'") && server.includes('https://api.nal.usda.gov/fdc/v1/foods/search'),'server proxies USDA FoodData Central');
assert(server.includes('process.env.FDC_API_KEY') && server.includes("'DEMO_KEY'"),'API key is server-side and rate-limited demo fallback exists');
assert(server.includes('q.length < 2') && server.includes('q.length > 80'),'query length is bounded');
assert(server.includes('searchWindowCount > 20'),'proxy rate limit exists');
assert(env.includes('FDC_API_KEY='),'key configuration documented');
assert(html.includes('Branded-food records may be per serving') && html.toLowerCase().includes('verify the food form'),'food data verification warning exists');
assert(!html.includes('<p><strong>How to use it:</strong>'),'food guidance no longer renders preparation/combination tips');
console.log('PASS USDA FoodData Central lookup UI');
console.log('PASS same-origin server-side proxy and private key configuration');
console.log('PASS bounded queries, local rate limit, and data-source warning');
console.log('PASS food-source guidance avoids recipe/preparation instructions');
