'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const p = path.join(__dirname,'production_preflight.js');
assert(fs.existsSync(p),'preflight script exists');
const src = fs.readFileSync(p,'utf8');
for (const token of ['DATABASE_URL','REVILAC_HTTPS_TERMINATED','SMTP_HOST','SMTP_USER','SMTP_PASS','SMTP_FROM','request_rate_limits','REVILAC_SESSION_SECRET','release-evidence','database-integration.json','security-review.json','privacy-review.json','clinical-review.json','device-e2e.json','backup-restore.json','monitoring.json','nutrition-data.json','ocr-benchmark.json','accessibility-review.json']) assert(src.includes(token),'checks '+token);
assert(src.includes('read-only evidence-based preflight'),'evidence-based read-only nature documented');
assert(src.includes('if (blockers.length) process.exitCode = 2'),'blockers produce nonzero exit code');
assert(src.includes('DATABASE_URL alone is not integration'),'database env var alone cannot pass');
assert(src.includes('production-server.js') && src.includes('migrations'),'production PostgreSQL API and migrations are checked');
assert(src.includes('environment flags are not accepted as proof'),'review evidence cannot be replaced by env flags');
assert(!src.includes('console.log(process.env'),'does not print raw environment values');
const run = spawnSync(process.execPath, [p], { cwd: __dirname, encoding: 'utf8', env: { PATH: process.env.PATH, NODE_ENV: 'test' } });
assert.strictEqual(run.status, 2, 'missing production evidence must keep release blocked');
assert(run.stdout.includes('\"productionReady\": false'), 'preflight reports productionReady false');
assert(run.stdout.includes('live connection and migration evidence are still required'), 'DATABASE_URL cannot bypass live database evidence');
assert(run.stdout.includes('environment flags are not accepted as proof'), 'missing review evidence is explicitly reported');
console.log('Production preflight tests: 23/23 passed');
